/// 규칙 창을 이 기기에서 이미 봤는지. 처음 들어온 게임이면 한 번 보여준다.
enum RulesSeen {
    static func check(_ kind: GameKind) -> Bool { UserDefaults.standard.bool(forKey: "rules.\(kind.rawValue)") }
    static func mark(_ kind: GameKind) { UserDefaults.standard.set(true, forKey: "rules.\(kind.rawValue)") }
}
